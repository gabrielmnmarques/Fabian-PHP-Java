    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int linha = linhaEscolhida();
        if (linha < 0) {
            return;
        }
        registro = lista.get(linha);
        escolherNaLista(cbFase, registro.getIdFase());
        txtInicioFase.setText(textoData(registro.getDtInicioFase()));
        txtTerminoFase.setText(textoData(registro.getDtTerminoFase()));
        cbFase.setEnabled(false); // a chave do vínculo não muda
        mostrarFormulario("ALTERAR · HISTÓRICO DE FASES", "Salvar");
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = linhaEscolhida();
        if (linha < 0) {
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "Excluir este registro?", "Excluir",
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) {
            return;
        }
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return;
        }
        Daoobras_fases dao = new Daoobras_fases(dataSource);
        dao.excluir(contexto, lista.get(linha).getIdFase());
        dataSource.closeDataSource();
        carregar();
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnGravarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGravarActionPerformed
        try {
            obras_fases prod = new obras_fases();
            prod.setIdObra(contexto);
            prod.setIdFase(registro != null ? registro.getIdFase() : codigoDaLista("Fase", cbFase));
            prod.setDtInicioFase(lerData("Início da fase", txtInicioFase.getText(), false));
            prod.setDtTerminoFase(lerData("Encerramento da fase", txtTerminoFase.getText(), false));
            validarPeriodo(prod.getDtInicioFase(), prod.getDtTerminoFase());
            if (registro == null) {
                for (obras_fases x : lista) {
                    if (x.getIdFase() == prod.getIdFase()) {
                        throw new IllegalArgumentException("Já existe um registro com esse código ou vínculo.");
                    }
                }
            }
            DataSource dataSource = new DataSource();
            if (dataSource.getConnection() == null) {
                return;
            }
            Daoobras_fases dao = new Daoobras_fases(dataSource);
            if (registro == null) {
                dao.incluir(prod);
            } else {
                dao.alterar(prod);
            }
            dataSource.closeDataSource();
            carregar();
            mostrarLista();
        } catch (IllegalArgumentException erro) {
            JOptionPane.showMessageDialog(this, erro.getMessage());
        }
    }//GEN-LAST:event_btnGravarActionPerformed

