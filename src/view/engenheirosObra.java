    /** Preenche as listas (o <select> do site) e guarda os nomes para a tabela. */
    private void carregarListas() {
        for (String nome : nomesDeObras().values()) {
            cbContexto.addItem(nome);
        }
        nomesEngenheiros = nomesDeEngenheiros();
        for (String nome : nomesEngenheiros.values()) {
            cbEngenheiro.addItem(nome);
        }
        nomesFuncoes = nomesDeFuncoes();
        for (String nome : nomesFuncoes.values()) {
            cbFuncao.addItem(nome);
        }
        dadosDosEngenheiros = dadosDosEngenheiros();
        btnAbrir.setEnabled(cbContexto.getItemCount() > 1);
        if (cbContexto.getItemCount() <= 1) {
            lblAviso.setText("Cadastre uma obra primeiro.");
        }
    }

    /** Lê os vínculos da obra escolhida e mostra na tabela. */
    private void carregar() {
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return;
        }
        ArrayList<obras_engenheiros> registros = new Daoobras_engenheiros(dataSource).consulta();
        dataSource.closeDataSource();
        lista = new ArrayList<>();
        if (registros != null) {
            for (obras_engenheiros x : registros) {
                if (x.getIdObra() == contexto) {
                    lista.add(x);
                }
            }
        }

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);
        for (obras_engenheiros prod : lista) {
            engenheiro dados = dadosDosEngenheiros.get(prod.getIdEngenheiro());
            modelo.addRow(new Object[]{nomesEngenheiros.getOrDefault(prod.getIdEngenheiro(), "—"), mostrarData(prod.getDtInicioTrabalho()), mostrarData(prod.getDtFimTrabalho()), nomesFuncoes.getOrDefault(prod.getIdFuncao(), "—"), dados == null ? "—" : mostrarData(dados.getDtAdmissao())});
        }
        ajustarAlturaDaTabela();
    }

    /** Obras para as listas e a tabela, como "Nome (código)". */
    private java.util.Map<Integer, String> nomesDeObras() {
        java.util.Map<Integer, String> nomes = new java.util.LinkedHashMap<>();
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return nomes;
        }
        ArrayList<obras> lista = new Daoobras(dataSource).consulta();
        dataSource.closeDataSource();
        if (lista != null) {
            lista.sort(java.util.Comparator.comparing(x -> String.valueOf(x.getDescricao()).toLowerCase()));
            for (obras x : lista) {
                nomes.put(x.getIdObra(), x.getDescricao() + " (" + x.getIdObra() + ")");
            }
        }
        return nomes;
    }

