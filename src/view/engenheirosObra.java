    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int linha = linhaEscolhida();
        if (linha < 0) {
            return;
        }
        registro = lista.get(linha);
        escolherNaLista(cbEngenheiro, registro.getIdEngenheiro());
        txtInicioTrabalho.setText(textoData(registro.getDtInicioTrabalho()));
        txtFimTrabalho.setText(textoData(registro.getDtFimTrabalho()));
        escolherNaLista(cbFuncao, registro.getIdFuncao());
        cbEngenheiro.setEnabled(false); // a chave do vínculo não muda
        mostrarFormulario("ALTERAR · ENGENHEIROS DA OBRA", "Salvar");
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = linhaEscolhida();
        if (linha < 0) {
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "Excluir este registro?", "Excluir",
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) {
            return;
        }
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return;
        }
        Daoobras_engenheiros dao = new Daoobras_engenheiros(dataSource);
        dao.excluir(contexto, lista.get(linha).getIdEngenheiro());
        dataSource.closeDataSource();
        carregar();
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnGravarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGravarActionPerformed
        try {
            obras_engenheiros prod = new obras_engenheiros();
            prod.setIdObra(contexto);
            prod.setIdEngenheiro(registro != null ? registro.getIdEngenheiro() : codigoDaLista("Engenheiro", cbEngenheiro));
            prod.setDtInicioTrabalho(lerData("Início do trabalho", txtInicioTrabalho.getText(), true));
            prod.setDtFimTrabalho(lerData("Fim do trabalho", txtFimTrabalho.getText(), false));
            prod.setIdFuncao(codigoDaLista("Função na obra", cbFuncao));
            validarPeriodo(prod.getDtInicioTrabalho(), prod.getDtFimTrabalho());
            if (registro == null) {
                for (obras_engenheiros x : lista) {
                    if (x.getIdEngenheiro() == prod.getIdEngenheiro()) {
                        throw new IllegalArgumentException("Já existe um registro com esse código ou vínculo.");
                    }
                }
            }
            DataSource dataSource = new DataSource();
            if (dataSource.getConnection() == null) {
                return;
            }
            Daoobras_engenheiros dao = new Daoobras_engenheiros(dataSource);
            if (registro == null) {
                dao.incluir(prod);
            } else {
                dao.alterar(prod);
            }
            dataSource.closeDataSource();
            carregar();
            mostrarLista();
        } catch (IllegalArgumentException erro) {
            JOptionPane.showMessageDialog(this, erro.getMessage());
        }
    }//GEN-LAST:event_btnGravarActionPerformed

