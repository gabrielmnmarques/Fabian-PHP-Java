    private void btnVoltarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVoltarActionPerformed
        if (registro != null) {
            mostrarLista(); // no formulário, Voltar volta para a lista
        } else {
            dispose();
        }
    }//GEN-LAST:event_btnVoltarActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int linha = linhaEscolhida();
        if (linha < 0) {
            return;
        }
        registro = lista.get(linha);
        txtIdFuncao.setText(String.valueOf(registro.getIdFuncao()));
        txtNomeFuncao.setText(registro.getDsFuncao());
        txtNomeFuncao.requestFocus();
        jPanelLista.setVisible(false);
        jPanelEditar.setVisible(true);
        getRootPane().setDefaultButton(btnSalvar);
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        try {
            funcoes prod = new funcoes();
            prod.setIdFuncao(registro.getIdFuncao());
            prod.setDsFuncao(obrigatorio("Nome da Função", txtNomeFuncao.getText()));
            DataSource dataSource = new DataSource();
            if (dataSource.getConnection() == null) {
                return;
            }
            Daofuncoes dao = new Daofuncoes(dataSource);
            dao.alterar(prod);
            dataSource.closeDataSource();
            carregar();
            mostrarLista();
        } catch (IllegalArgumentException erro) {
            JOptionPane.showMessageDialog(this, erro.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarActionPerformed
        mostrarLista();
    }//GEN-LAST:event_btnCancelarActionPerformed

    private void mostrarLista() {
        registro = null;
        getRootPane().setDefaultButton(null);
        jPanelEditar.setVisible(false);
        jPanelLista.setVisible(true);
    }

    private ArrayList<funcoes> lista = new ArrayList<>();

    /** Lê os registros do banco e mostra na tabela. */
    private void carregar() {
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return;
        }
        Daofuncoes dao = new Daofuncoes(dataSource);
        ArrayList<funcoes> registros = dao.consulta();
        dataSource.closeDataSource();
        lista = registros == null ? new ArrayList<>() : registros;

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);
        for (funcoes prod : lista) {
            modelo.addRow(new Object[]{prod.getIdFuncao(), prod.getDsFuncao()});
        }
        ajustarAlturaDaTabela();
    }

    /** Texto obrigatório (mesma mensagem do site). */
    private static String obrigatorio(String nome, String texto) {
        String valor = texto.trim();
        if (valor.isEmpty()) {
            throw new IllegalArgumentException("Preencha o campo " + nome + ".");
        }
        return valor;
    }

    /** Linha escolhida na tabela, ou -1 com o aviso. */
    private int linhaEscolhida() {
        int linha = jTable1.getSelectedRow();
        if (linha < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um registro na tabela.");
        }
        return linha;
    }

    /** Cabeçalho cinza, linhas zebradas e espaçamento da tabela do site. */
    private void estilizarTabela() {
        jTable1.getTableHeader().setReorderingAllowed(false);
        jTable1.getTableHeader().setDefaultRenderer(new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable tabela, Object valor,
                    boolean selecionada, boolean foco, int linha, int coluna) {
                super.getTableCellRendererComponent(tabela, valor, false, false, linha, coluna);
                setFont(new java.awt.Font("Segoe UI", 1, 13));
                setForeground(new java.awt.Color(39, 39, 39));
                setBackground(new java.awt.Color(241, 241, 241));
                setBorder(javax.swing.BorderFactory.createCompoundBorder(
                        javax.swing.BorderFactory.createMatteBorder(0, 0, 1, 0, new java.awt.Color(222, 222, 222)),
                        javax.swing.BorderFactory.createEmptyBorder(11, 12, 11, 12)));
                return this;
            }
        });
        jTable1.setDefaultRenderer(Object.class, new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable tabela, Object valor,
                    boolean selecionada, boolean foco, int linha, int coluna) {
                super.getTableCellRendererComponent(tabela, valor, selecionada, false, linha, coluna);
                if (!selecionada) {
                    setBackground(linha % 2 == 0 ? java.awt.Color.WHITE : new java.awt.Color(248, 248, 248));
                }
                setBorder(javax.swing.BorderFactory.createEmptyBorder(0, 12, 0, 12));
                return this;
            }
        });
        jScrollPane1.getViewport().setBackground(java.awt.Color.WHITE);
    }

    /** A caixa da tabela cresce com as linhas, até um limite. */
    private void ajustarAlturaDaTabela() {
        int altura = 48 + Math.max(jTable1.getRowCount(), 1) * jTable1.getRowHeight();
        jScrollPane1.setPreferredSize(new java.awt.Dimension(600, Math.min(altura, 400)));
        jPanelCartao.revalidate();
    }

