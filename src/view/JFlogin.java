    private void btnSairActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSairActionPerformed
        for (javax.swing.JInternalFrame tela : jDesktopPane1.getAllFrames()) {
            tela.dispose();
        }
        menu = null;
        jPanelBarra.setVisible(false);
        ((java.awt.CardLayout) jPanelConteudo.getLayout()).show(jPanelConteudo, "login");
        txtSenha.setText("");
        txtEmail.requestFocus();
    }//GEN-LAST:event_btnSairActionPerformed

    private void mostrarErro(String mensagem) {
        lblErro.setText(mensagem);
        lblErro.setVisible(true);
        jPanelLogin.revalidate();
    }

    /** Depois do login: mostra a barra do topo e o menu. */
    private void entrar() {
        lblErro.setVisible(false);
        txtSenha.setText("");
        jPanelBarra.setVisible(true);
        ((java.awt.CardLayout) jPanelConteudo.getLayout()).show(jPanelConteudo, "sistema");
        jPanelConteudo.validate();
        menu = new menuFinal();
        abrirTela(menu);
    }

    /** Marca "Balança-Mas-Não-Cai" da barra: fecha a tela aberta e volta ao menu. */
    private void voltarAoMenu() {
        for (javax.swing.JInternalFrame tela : jDesktopPane1.getAllFrames()) {
            if (tela != menu) {
                tela.dispose();
            }
        }
    }

    /**
     * Abre uma tela ocupando a área toda, sem barra de título, como uma página
     * do site. Fica só uma tela aberta por cima do menu; o "← Voltar" de cada
     * tela faz dispose() e o menu aparece de novo.
     */
    public static void abrirTela(javax.swing.JInternalFrame tela) {
        javax.swing.JDesktopPane area = principal.jDesktopPane1;
        for (javax.swing.JInternalFrame aberta : area.getAllFrames()) {
            if (aberta != principal.menu) {
                aberta.dispose();
            }
        }
        tela.setBorder(null);
        ((javax.swing.plaf.basic.BasicInternalFrameUI) tela.getUI()).setNorthPane(null);
        area.add(tela);
        tela.setBounds(0, 0, area.getWidth(), area.getHeight());
        tela.setVisible(true);
        try {
            tela.setSelected(true);
        } catch (java.beans.PropertyVetoException erro) {
            // a tela continua aberta mesmo sem o foco
        }
    }

