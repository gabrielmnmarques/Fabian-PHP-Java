    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int linha = linhaEscolhida();
        if (linha < 0) {
            return;
        }
        registro = lista.get(linha);
        escolherNaLista(cbObra, registro.getIdObra());
        txtDataInicial.setText(textoData(registro.getDtInicio()));
        txtDataFinal.setText(textoData(registro.getDtFim()));
        txtValorPrevisto.setText(mostrarValor(registro.getVlPrevisto()));
        txtValorRealizado.setText(mostrarValor(registro.getVlRealizado()));
        cbObra.setEnabled(false); // a chave do vínculo não muda
        mostrarFormulario("ALTERAR · OBRAS DO ORÇAMENTO", "Salvar");
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = linhaEscolhida();
        if (linha < 0) {
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "Excluir este registro?", "Excluir",
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) {
            return;
        }
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return;
        }
        Daoorcamentos_obras dao = new Daoorcamentos_obras(dataSource);
        dao.excluir(contexto, lista.get(linha).getIdObra());
        dataSource.closeDataSource();
        carregar();
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnGravarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGravarActionPerformed
        try {
            orcamentos_obras prod = new orcamentos_obras();
            prod.setIdOrcamento(contexto);
            prod.setIdObra(registro != null ? registro.getIdObra() : codigoDaLista("Obra", cbObra));
            prod.setDtInicio(lerData("Data inicial", txtDataInicial.getText(), false));
            prod.setDtFim(lerData("Data final", txtDataFinal.getText(), false));
            prod.setVlPrevisto(lerValor("Valor previsto", txtValorPrevisto.getText()));
            prod.setVlRealizado(lerValor("Valor realizado", txtValorRealizado.getText()));
            validarPeriodo(prod.getDtInicio(), prod.getDtFim());
            if (registro == null) {
                for (orcamentos_obras x : lista) {
                    if (x.getIdObra() == prod.getIdObra()) {
                        throw new IllegalArgumentException("Já existe um registro com esse código ou vínculo.");
                    }
                }
            }
            DataSource dataSource = new DataSource();
            if (dataSource.getConnection() == null) {
                return;
            }
            Daoorcamentos_obras dao = new Daoorcamentos_obras(dataSource);
            if (registro == null) {
                dao.incluir(prod);
            } else {
                dao.alterar(prod);
            }
            dataSource.closeDataSource();
            carregar();
            mostrarLista();
        } catch (IllegalArgumentException erro) {
            JOptionPane.showMessageDialog(this, erro.getMessage());
        }
    }//GEN-LAST:event_btnGravarActionPerformed

