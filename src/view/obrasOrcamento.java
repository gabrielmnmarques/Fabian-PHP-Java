    /** Preenche as listas (o <select> do site) e guarda os nomes para a tabela. */
    private void carregarListas() {
        for (String nome : nomesDeOrcamentos().values()) {
            cbContexto.addItem(nome);
        }
        nomesObras = nomesDeObras();
        for (String nome : nomesObras.values()) {
            cbObra.addItem(nome);
        }
        btnAbrir.setEnabled(cbContexto.getItemCount() > 1);
        if (cbContexto.getItemCount() <= 1) {
            lblAviso.setText("Cadastre um orçamento primeiro.");
        }
    }

    /** Lê os vínculos do orçamento escolhido e mostra na tabela. */
    private void carregar() {
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return;
        }
        ArrayList<orcamentos_obras> registros = new Daoorcamentos_obras(dataSource).consulta();
        dataSource.closeDataSource();
        lista = new ArrayList<>();
        if (registros != null) {
            for (orcamentos_obras x : registros) {
                if (x.getIdOrcamento() == contexto) {
                    lista.add(x);
                }
            }
        }

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);
        double previsto = 0;
        double realizado = 0;
        for (orcamentos_obras prod : lista) {
            modelo.addRow(new Object[]{nomesObras.getOrDefault(prod.getIdObra(), "—"), mostrarData(prod.getDtInicio()), mostrarData(prod.getDtFim()), "R$ " + mostrarValor(prod.getVlPrevisto()), "R$ " + mostrarValor(prod.getVlRealizado())});
            previsto += prod.getVlPrevisto();
            realizado += prod.getVlRealizado();
        }
        lblTotais.setText("<html><b>Total previsto</b>&nbsp; R$ " + mostrarValor(previsto)
                + "&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; <b>Total realizado</b>&nbsp; R$ " + mostrarValor(realizado) + "</html>");
        ajustarAlturaDaTabela();
    }

    /** Orcamentos para as listas e a tabela, como "Nome (código)". */
    private java.util.Map<Integer, String> nomesDeOrcamentos() {
        java.util.Map<Integer, String> nomes = new java.util.LinkedHashMap<>();
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return nomes;
        }
        ArrayList<orcamento> lista = new Daoorcamento(dataSource).consulta();
        dataSource.closeDataSource();
        if (lista != null) {
            for (orcamento x : lista) {
                nomes.put(x.getIdOrcamento(), "Orçamento nº " + x.getIdOrcamento());
            }
        }
        return nomes;
    }

    /** Obras para as listas e a tabela, como "Nome (código)". */
    private java.util.Map<Integer, String> nomesDeObras() {
        java.util.Map<Integer, String> nomes = new java.util.LinkedHashMap<>();
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return nomes;
        }
        ArrayList<obras> lista = new Daoobras(dataSource).consulta();
        dataSource.closeDataSource();
        if (lista != null) {
            lista.sort(java.util.Comparator.comparing(x -> String.valueOf(x.getDescricao()).toLowerCase()));
            for (obras x : lista) {
                nomes.put(x.getIdObra(), x.getDescricao() + " (" + x.getIdObra() + ")");
            }
        }
        return nomes;
    }

    /** Lê uma data no formato dd/mm/aaaa. */
    private static java.sql.Date lerData(String nome, String texto, boolean obrigatoria) {
        String valor = texto.trim();
        if (valor.isEmpty()) {
            if (obrigatoria) {
                throw new IllegalArgumentException("Preencha o campo " + nome + ".");
            }
            return null;
        }
        try {
            java.time.format.DateTimeFormatter formato = java.time.format.DateTimeFormatter
                    .ofPattern("dd/MM/uuuu").withResolverStyle(java.time.format.ResolverStyle.STRICT);
            return java.sql.Date.valueOf(java.time.LocalDate.parse(valor, formato));
        } catch (java.time.format.DateTimeParseException erro) {
            throw new IllegalArgumentException("Valor inválido em " + nome + ". Use dd/mm/aaaa.");
        }
    }

    /** Data para o campo de texto (vazio quando não tem data). */
    private static String textoData(java.sql.Date data) {
        return data == null ? "" : new java.text.SimpleDateFormat("dd/MM/yyyy").format(data);
    }

    /** Data para a tabela ("—" quando não tem data, como no site). */
    private static String mostrarData(java.sql.Date data) {
        return data == null ? "—" : new java.text.SimpleDateFormat("dd/MM/yyyy").format(data);
    }

    /** Mesma regra do site: a data final não pode vir antes da inicial. */
    private static void validarPeriodo(java.sql.Date inicio, java.sql.Date fim) {
        if (fim != null && (inicio == null || fim.before(inicio))) {
            throw new IllegalArgumentException("Informe uma data inicial válida e uma data final igual ou posterior.");
        }
    }

    /** Código escolhido na lista ("Nome (código)" ou "Orçamento nº código"). */
    private static int codigoDaLista(String nome, javax.swing.JComboBox<String> lista) {
        String item = (String) lista.getSelectedItem();
        if (lista.getSelectedIndex() <= 0 || item == null) {
            throw new IllegalArgumentException("Preencha o campo " + nome + ".");
        }
        if (item.endsWith(")")) {
            return Integer.parseInt(item.substring(item.lastIndexOf('(') + 1, item.length() - 1));
        }
        return Integer.parseInt(item.substring(item.lastIndexOf(' ') + 1));
    }

    private static void escolherNaLista(javax.swing.JComboBox<String> lista, int codigo) {
        lista.setSelectedIndex(0);
        for (int i = 1; i < lista.getItemCount(); i++) {
            String item = lista.getItemAt(i);
            if (item.endsWith("(" + codigo + ")") || item.endsWith("nº " + codigo)) {
                lista.setSelectedIndex(i);
            }
        }
    }

    /** Valor em reais: aceita 1500, 1500,50 ou 1.500,50. Em branco = 0,00. */
    private static double lerValor(String nome, String texto) {
        String valor = texto.trim().replace("R$", "").trim();
        if (valor.isEmpty()) {
            return 0;
        }
        if (valor.contains(",")) {
            valor = valor.replace(".", "").replace(',', '.');
        }
        try {
            double numero = Double.parseDouble(valor);
            if (numero < 0 || numero > 99999999.99) {
                throw new NumberFormatException();
            }
            return numero;
        } catch (NumberFormatException erro) {
            throw new IllegalArgumentException("Valor inválido em " + nome + ".");
        }
    }

    private static String mostrarValor(double valor) {
        java.text.NumberFormat formato = java.text.NumberFormat.getNumberInstance(java.util.Locale.forLanguageTag("pt-BR"));
        formato.setMinimumFractionDigits(2);
        formato.setMaximumFractionDigits(2);
        return formato.format(valor);
    }

