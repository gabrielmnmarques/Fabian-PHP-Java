    private void btnIncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIncluirActionPerformed
        try {
            engenheiro prod = new engenheiro();
            prod.setDsNome(obrigatorio("Nome do Engenheiro", txtNome.getText()));
            prod.setNrCREA(obrigatorio("Informe o número do CREA", txtCrea.getText()));
            prod.setDtAdmissao(lerData("Data de Admissão", txtDataAdmissao.getText(), true));
            DataSource dataSource = new DataSource();
            if (dataSource.getConnection() == null) {
                return;
            }
            Daoengenheiros dao = new Daoengenheiros(dataSource);
            dao.incluir(prod);
            dataSource.closeDataSource();
            limpar();
        } catch (IllegalArgumentException erro) {
            JOptionPane.showMessageDialog(this, erro.getMessage());
        }
    }//GEN-LAST:event_btnIncluirActionPerformed

