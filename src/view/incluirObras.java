    private void btnIncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIncluirActionPerformed
        try {
            obras prod = new obras();
            prod.setIdObra(lerCodigo("Id da Obra", txtIdObra.getText()));
            prod.setDescricao(obrigatorio("Nome da Obra", txtNomeObra.getText()));
            prod.setDtInicio(lerData("Data de Início", txtDataInicio.getText(), true));
            prod.setDtFim(lerData("Data do Fim", txtDataFim.getText(), false));
            prod.setIdEngenehrio(codigoDaLista("Engenheiro responsável", cbEngenheiro));
            validarPeriodo(prod.getDtInicio(), prod.getDtFim());
            DataSource dataSource = new DataSource();
            if (dataSource.getConnection() == null) {
                return;
            }
            Daoobras dao = new Daoobras(dataSource);
            dao.incluir(prod);
            dataSource.closeDataSource();
            limpar();
        } catch (IllegalArgumentException erro) {
            JOptionPane.showMessageDialog(this, erro.getMessage());
        }
    }//GEN-LAST:event_btnIncluirActionPerformed

