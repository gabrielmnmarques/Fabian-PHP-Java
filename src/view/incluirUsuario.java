    private void btnIncluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIncluirActionPerformed
        try {
            usuarios prod = new usuarios();
            prod.setIdUsuario(lerCodigo("Código do Usuário", txtIdUsuario.getText()));
            prod.setNome(obrigatorio("Nome do Usuário", txtNome.getText()));
            prod.setEmail(lerEmail("E-mail", txtEmail.getText()));
            prod.setSenha(obrigatorio("Senha do Usuário", new String(txtSenha.getPassword())));
            DataSource dataSource = new DataSource();
            if (dataSource.getConnection() == null) {
                return;
            }
            Daousuario dao = new Daousuario(dataSource);
            dao.incluir(prod);
            dataSource.closeDataSource();
            limpar();
        } catch (IllegalArgumentException erro) {
            JOptionPane.showMessageDialog(this, erro.getMessage());
        }
    }//GEN-LAST:event_btnIncluirActionPerformed

