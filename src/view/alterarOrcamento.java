    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        try {
            orcamento prod = new orcamento();
            prod.setIdOrcamento(registro.getIdOrcamento());
            prod.setDtAprovacao(lerData("Data de aprovação", txtDataAprovacao.getText(), false));
            prod.setIdEngenheiroResponsavel(codigoDaLista("Responsável pela elaboração", cbEngenheiro));
            DataSource dataSource = new DataSource();
            if (dataSource.getConnection() == null) {
                return;
            }
            Daoorcamento dao = new Daoorcamento(dataSource);
            dao.alterar(prod);
            dataSource.closeDataSource();
            carregar();
            mostrarLista();
        } catch (IllegalArgumentException erro) {
            JOptionPane.showMessageDialog(this, erro.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

