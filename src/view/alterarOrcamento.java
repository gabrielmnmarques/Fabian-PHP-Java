    private ArrayList<orcamento> lista = new ArrayList<>();

    /** Lê os registros do banco e mostra na tabela. */
    private void carregar() {
        java.util.Map<Integer, String> nomesEngenheiros = nomesDeEngenheiros();
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return;
        }
        Daoorcamento dao = new Daoorcamento(dataSource);
        ArrayList<orcamento> registros = dao.consulta();
        dataSource.closeDataSource();
        lista = registros == null ? new ArrayList<>() : registros;

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);
        for (orcamento prod : lista) {
            modelo.addRow(new Object[]{prod.getIdOrcamento(), mostrarData(prod.getDtAprovacao()), nomesEngenheiros.getOrDefault(prod.getIdEngenheiroResponsavel(), "—")});
        }
        ajustarAlturaDaTabela();
    }

    /** Preenche as listas (o <select> do site). */
    private void carregarListas() {
        for (String nome : nomesDeEngenheiros().values()) {
            cbEngenheiro.addItem(nome);
        }
    }

    /** Engenheiros para as listas e a tabela, como "Nome (código)". */
    private java.util.Map<Integer, String> nomesDeEngenheiros() {
        java.util.Map<Integer, String> nomes = new java.util.LinkedHashMap<>();
        DataSource dataSource = new DataSource();
        if (dataSource.getConnection() == null) {
            return nomes;
        }
        ArrayList<engenheiro> lista = new Daoengenheiros(dataSource).consulta();
        dataSource.closeDataSource();
        if (lista != null) {
            lista.sort(java.util.Comparator.comparing(x -> String.valueOf(x.getDsNome()).toLowerCase()));
            for (engenheiro x : lista) {
                nomes.put(x.getIdEngenheiro(), x.getDsNome() + " (" + x.getIdEngenheiro() + ")");
            }
        }
        return nomes;
    }

    /** Lê uma data no formato dd/mm/aaaa. */
    private static java.sql.Date lerData(String nome, String texto, boolean obrigatoria) {
        String valor = texto.trim();
        if (valor.isEmpty()) {
            if (obrigatoria) {
                throw new IllegalArgumentException("Preencha o campo " + nome + ".");
            }
            return null;
        }
        try {
            java.time.format.DateTimeFormatter formato = java.time.format.DateTimeFormatter
                    .ofPattern("dd/MM/uuuu").withResolverStyle(java.time.format.ResolverStyle.STRICT);
            return java.sql.Date.valueOf(java.time.LocalDate.parse(valor, formato));
        } catch (java.time.format.DateTimeParseException erro) {
            throw new IllegalArgumentException("Valor inválido em " + nome + ". Use dd/mm/aaaa.");
        }
    }

    /** Data para o campo de texto (vazio quando não tem data). */
    private static String textoData(java.sql.Date data) {
        return data == null ? "" : new java.text.SimpleDateFormat("dd/MM/yyyy").format(data);
    }

    /** Data para a tabela ("—" quando não tem data, como no site). */
    private static String mostrarData(java.sql.Date data) {
        return data == null ? "—" : new java.text.SimpleDateFormat("dd/MM/yyyy").format(data);
    }

    /** Código escolhido na lista ("Nome (código)" ou "Orçamento nº código"). */
    private static int codigoDaLista(String nome, javax.swing.JComboBox<String> lista) {
        String item = (String) lista.getSelectedItem();
        if (lista.getSelectedIndex() <= 0 || item == null) {
            throw new IllegalArgumentException("Preencha o campo " + nome + ".");
        }
        if (item.endsWith(")")) {
            return Integer.parseInt(item.substring(item.lastIndexOf('(') + 1, item.length() - 1));
        }
        return Integer.parseInt(item.substring(item.lastIndexOf(' ') + 1));
    }

    private static void escolherNaLista(javax.swing.JComboBox<String> lista, int codigo) {
        lista.setSelectedIndex(0);
        for (int i = 1; i < lista.getItemCount(); i++) {
            String item = lista.getItemAt(i);
            if (item.endsWith("(" + codigo + ")") || item.endsWith("nº " + codigo)) {
                lista.setSelectedIndex(i);
            }
        }
    }

    /** Linha escolhida na tabela, ou -1 com o aviso. */
    private int linhaEscolhida() {
        int linha = jTable1.getSelectedRow();
        if (linha < 0) {
            JOptionPane.showMessageDialog(this, "Selecione um registro na tabela.");
        }
        return linha;
    }

